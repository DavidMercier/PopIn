function answer = popin_energy_input(prompts, defaults)
answer = {};
dialog = uifigure('Name', 'Confirm event and energy assumptions', ...
    'Tag', 'PopInEnergyInputs', 'Position', [100 100 900 600], ...
    'CloseRequestFcn', @cancel_dialog);
cleanup = onCleanup(@() delete(dialog));
layout = uigridlayout(dialog, [18 1]);
layout.RowHeight = [{26}, repmat({22, 28}, 1, 8), {32}];
layout.Padding = [12 12 12 12];
layout.RowSpacing = 5;
uilabel(layout, 'Text', ...
    'Click a blue input label for definitions, units and examples. Leave unknown physics inputs blank.');
fields = gobjects(numel(prompts), 1);
for k = 1:numel(prompts)
    uihyperlink(layout, 'Text', prompts{k}, 'URL', '', ...
        'Tooltip', 'Explain this input without changing your entries', ...
        'HyperlinkClickedFcn', @(~, ~) explain_term(k));
    fields(k) = uieditfield(layout, 'text', 'Value', defaults{k}, ...
        'Tag', sprintf('PopInEnergyInput%d', k));
end
buttons = uigridlayout(layout, [1 2]);
buttons.Padding = [0 0 0 0];
uibutton(buttons, 'Text', 'OK', 'ButtonPushedFcn', @accept_dialog);
uibutton(buttons, 'Text', 'Cancel', 'ButtonPushedFcn', @cancel_dialog);
uiwait(dialog);
clear cleanup;

    function accept_dialog(~, ~)
        answer = cell(numel(fields), 1);
        for field = 1:numel(fields)
            answer{field} = fields(field).Value;
        end
        uiresume(dialog);
    end

    function cancel_dialog(~, ~)
        uiresume(dialog);
    end
end

